#!/bin/bash

# Setup script for MCP Genmedia environment configuration
# This script helps configure your environment for using the MCP Genmedia servers

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}=== MCP Genmedia Environment Setup ===${NC}"
echo

# Function to detect shell configuration file
detect_shell_config() {
    if [ -n "$ZSH_VERSION" ]; then
        echo "$HOME/.zshrc"
    elif [ -n "$BASH_VERSION" ]; then
        if [ -f "$HOME/.bash_profile" ]; then
            echo "$HOME/.bash_profile"
        else
            echo "$HOME/.bashrc"
        fi
    else
        echo "$HOME/.profile"
    fi
}

SHELL_CONFIG=$(detect_shell_config)

# Check if Go bin is in PATH
if [[ ! ":$PATH:" == *":$HOME/go/bin:"* ]]; then
    echo -e "${YELLOW}Adding Go bin directory to PATH...${NC}"
    echo "" >> "$SHELL_CONFIG"
    echo "# Go binary path (added by MCP Genmedia setup)" >> "$SHELL_CONFIG"
    echo "export PATH=\"\$PATH:\$HOME/go/bin\"" >> "$SHELL_CONFIG"
    echo -e "${GREEN}✓ Added Go bin to PATH in $SHELL_CONFIG${NC}"
    export PATH="$PATH:$HOME/go/bin"
else
    echo -e "${GREEN}✓ Go bin is already in PATH${NC}"
fi

# Get current Google Cloud project
CURRENT_PROJECT=$(gcloud config get project 2>/dev/null || echo "")

if [ -z "$CURRENT_PROJECT" ]; then
    echo -e "${RED}No Google Cloud project is currently set.${NC}"
    echo "Please run: gcloud config set project YOUR_PROJECT_ID"
    exit 1
else
    echo -e "${GREEN}✓ Using Google Cloud project: ${CURRENT_PROJECT}${NC}"
fi

# Create environment file
ENV_FILE="$(pwd)/.env"
echo -e "\n${BLUE}Creating environment configuration...${NC}"

cat > "$ENV_FILE" << EOF
# MCP Genmedia Environment Variables
# Generated by setup_environment.sh on $(date)

# Google Cloud Project Configuration
export PROJECT_ID="${CURRENT_PROJECT}"
export LOCATION="us-central1"

# Google Cloud Storage bucket for media assets
# Update this to your actual GCS bucket name
export GENMEDIA_BUCKET="your-gcs-bucket-name"

# Server port for HTTP mode (default: 8080)
export PORT="8080"

# OpenTelemetry configuration for local development
# Uncomment these for local development with OTel collector
# export OTEL_EXPORTER_OTLP_INSECURE=true
# export OTEL_EXPORTER_OTLP_ENDPOINT="localhost:4317"
EOF

echo -e "${GREEN}✓ Created environment file: $ENV_FILE${NC}"
echo -e "${YELLOW}  Please edit this file and update GENMEDIA_BUCKET with your actual GCS bucket name${NC}"

# Check Google Cloud authentication
echo -e "\n${BLUE}Checking Google Cloud authentication...${NC}"
if gcloud auth application-default print-access-token &>/dev/null; then
    echo -e "${GREEN}✓ Application Default Credentials are configured${NC}"
else
    echo -e "${YELLOW}⚠ Application Default Credentials not found${NC}"
    echo "  Run: gcloud auth application-default login"
fi

# Test MCP servers installation
echo -e "\n${BLUE}Testing MCP servers installation...${NC}"
if command -v mcp-imagen-go &> /dev/null; then
    echo -e "${GREEN}✓ MCP servers are accessible in PATH${NC}"
else
    echo -e "${YELLOW}⚠ MCP servers not found in PATH${NC}"
    echo "  You may need to restart your shell or run: source $SHELL_CONFIG"
fi

# Create a test script
TEST_SCRIPT="test_mcp_servers.sh"
cat > "$TEST_SCRIPT" << 'EOF'
#!/bin/bash

# Test script for MCP servers
source .env

echo "Testing MCP servers with PROJECT_ID=$PROJECT_ID"
echo

for server in mcp-imagen-go mcp-veo-go mcp-chirp3-go mcp-lyria-go mcp-avtool-go; do
    echo -n "Testing $server... "
    if echo '{"jsonrpc":"2.0","method":"tools/list","id":1}' | $server 2>/dev/null | grep -q '"jsonrpc"'; then
        echo "✓ OK"
    else
        echo "✗ FAILED"
    fi
done
EOF

chmod +x "$TEST_SCRIPT"
echo -e "${GREEN}✓ Created test script: $TEST_SCRIPT${NC}"

# Instructions
echo -e "\n${BLUE}=== Setup Complete ===${NC}"
echo
echo "Next steps:"
echo "1. Edit $ENV_FILE and set your GENMEDIA_BUCKET"
echo "2. Source the environment: source $ENV_FILE"
echo "3. If needed, authenticate: gcloud auth application-default login"
echo "4. Test the servers: ./$TEST_SCRIPT"
echo
echo "To use the MCP servers:"
echo "  - STDIO mode: mcp-imagen-go"
echo "  - HTTP mode: mcp-imagen-go --transport http"
echo
echo -e "${YELLOW}Note: You may need to restart your shell or run:${NC}"
echo -e "${BLUE}  source $SHELL_CONFIG${NC}"
echo
